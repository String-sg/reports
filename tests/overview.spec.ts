import { test, expect } from '@playwright/test'

test('North Star, collapsed history and dedicated changelog remain usable on desktop and mobile', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.north-star')).toContainText('1,800+')
  await expect(page.locator('.north-star .status')).toHaveText('1,800+')
  await expect(page.locator('.credit')).toHaveText(['By Jiaen','Inspired by Sengkwang','By Tiannuo, Evan and Matthew'])
  await expect(page.getByText('String impact', { exact: true })).toHaveCount(0)
  await expect(page.locator('.legacy-products')).not.toHaveAttribute('open', '')
  await page.locator('.legacy-products > summary').click()
  await expect(page.locator('.legacy-products')).toContainText('Remarks Co-Pilot')
  await expect(page.locator('.legacy-products')).toContainText('1,000+')
  await page.locator('.legacy-products > summary').press('Enter')
  await expect(page.locator('.legacy-products')).not.toHaveAttribute('open', '')
  await expect(page.locator('footer')).toHaveCount(1)
  await expect(page.locator('footer').getByRole('link', { name:'Sign up' })).toHaveAttribute('href','https://id.string.sg/')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('link', { name:'Changelog', exact:true }).click()
  await expect(page).toHaveURL(/\/changelog$/)
  await expect(page.locator('.change-entry')).toHaveCount(12)
  await expect(page.locator('.change-entry').last()).toContainText('remain pending')
  await expect(page.locator('footer')).toHaveCount(1)
  await page.getByRole('link', { name:'← Back to reports', exact:true }).click()
  await expect(page).toHaveURL(/\/$/)
})
